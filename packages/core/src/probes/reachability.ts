import { describeError, type Logger } from '@ms/shared';

/**
 * Which probes are reachable, and what that means for their sensors (`R-05`).
 *
 * **A lost probe is one alarm, not a thousand.** When a probe stops answering, the sensors it
 * carries have not failed — nobody has asked them anything. Reporting them Down would be a claim
 * the system cannot support and would page whoever is on call with one alarm per sensor for a
 * single cable. `WORKFLOW.MD §12` and `docs/state-machine.md` layer 3 already say the right
 * thing: those sensors are **Unknown, cause `probe`**, and the one alarm comes from Probe Health.
 * This is the wiring that makes it happen — the state machine has always known how to answer,
 * and until now nothing ever told it the probe was gone.
 *
 * **Held in memory and never persisted, deliberately.** `probeReachable` is a live fact about a
 * TCP connection; a value read back from a table would be a claim about the past. A core that
 * has just started has not yet learned that a probe is missing, so `loadRuntimes` restores it
 * optimistically — and restoring it pessimistically would write a "probe unreachable" transition
 * for every sensor in the installation on every restart, an alarm storm generated by the restart
 * itself. The cost of the optimistic answer is one interval of staleness after a restart, which
 * the probe's own reconnect or its absence corrects.
 */

interface Db {
  query<T extends Record<string, unknown>>(text: string, values?: readonly unknown[]): Promise<T[]>;
  tx<T>(fn: (q: Queryable) => Promise<T>): Promise<T>;
}

interface Queryable {
  query<T extends Record<string, unknown>>(text: string, values?: readonly unknown[]): Promise<T[]>;
}

/** What this needs from the state service: re-decide these sensors, and say how many moved. */
export interface StateReevaluator {
  reevaluate(
    q: Queryable,
    sensorIds: readonly number[],
    at: Date,
    cause: { message: string },
  ): Promise<number>;
}

export interface ProbeReachabilityOptions {
  db: Db;
  logger: Logger;
  states: StateReevaluator;
  /**
   * Sensor types the **core** evaluates, which a probe outage does not touch (`P-13`).
   *
   * Found while building Probe Health, and it was already wrong for `core.factory`. A
   * core-evaluated sensor's readings come from rows this process holds; the probe it happens to
   * sit under has never scanned it and its absence changes nothing about it. Marking it Unknown
   * for that reason is a false claim — and for Probe Health specifically it is a disabling one,
   * because the sensor whose job is to raise the single alarm for a lost probe would be silenced
   * by the very outage it exists to report.
   *
   * Absent, nothing is excluded, which is the behaviour before this.
   */
  coreEvaluatedTypes?: readonly string[];
  now?: () => Date;
}

/**
 * Why a probe's sensors are Unknown.
 *
 * `link` is `R-05`: the connection went away, so nobody is asking. `silence` is `P-74`: the
 * connection is fine and nothing is coming back, which the sensors cannot tell apart and an
 * operator very much can.
 */
export type OfflineReason = 'link' | 'silence';

export class ProbeReachability {
  readonly #db: Db;
  readonly #logger: Logger;
  readonly #states: StateReevaluator;
  readonly #coreEvaluatedTypes: readonly string[];
  readonly #now: () => Date;

  /**
   * The sensors whose probe is currently gone.
   *
   * Sensor ids rather than probe ids, because the question asked of it — a hundred times a
   * second, once per sensor whose state is being decided — is "is *this* sensor's probe up".
   * Answering that from probe ids would mean walking the tree for every sensor on every
   * decision; a set of at most the installation's sensor count is a few hundred kilobytes at
   * the v1 target of 5,000 and answers in constant time.
   */
  readonly #unreachable = new Set<number>();
  /** Which probe put each sensor in that set, so one probe's return frees only its own. */
  /**
   * Why each probe's sensors are Unknown, alongside which they are.
   *
   * **The reason is here so that only its owner can clear it** (`P-74`). A probe that is
   * connected and silent and a probe whose link has gone both put their sensors in the same set,
   * because the sensors' answer is the same — but the delivery sweep must not decide a
   * *disconnected* probe is fine again just because it has stopped expecting results from it.
   * `found` is the link's, `resumed` is the sweep's, and neither undoes the other's work.
   */
  readonly #byProbe = new Map<number, { sensorIds: number[]; reason: OfflineReason }>();
  #outages = 0;

  constructor(options: ProbeReachabilityOptions) {
    this.#db = options.db;
    this.#logger = options.logger.child({ component: 'probe-reachability' });
    this.#states = options.states;
    this.#coreEvaluatedTypes = options.coreEvaluatedTypes ?? [];
    this.#now = options.now ?? ((): Date => new Date());
  }

  stats(): {
    probesDown: number;
    probesSilent: number;
    sensorsUnknown: number;
    outages: number;
  } {
    // **Split by reason** (`P-80`). `probesDown` is published to Core Health as 'Probes not
    // connected', and `P-74` began putting `reason: 'silence'` entries into this same map — for
    // probes whose session is up and heartbeating. The number then contradicted that probe's own
    // Probe Health, which reported it connected, and sent operators looking for a network fault
    // while the true signal was buried under the disagreement.
    let silent = 0;
    for (const held of this.#byProbe.values()) if (held.reason === 'silence') silent += 1;
    return {
      probesDown: this.#byProbe.size - silent,
      probesSilent: silent,
      sensorsUnknown: this.#unreachable.size,
      outages: this.#outages,
    };
  }

  /**
   * Why this probe's sensors are Unknown, or `undefined` if they are not.
   *
   * **So a caller can tell an edge from a level without keeping its own copy.** The delivery
   * sweep did keep one, and the copy could diverge from this in the one direction that matters:
   * it recorded a probe as marked *before* `lost` had succeeded, and `lost` logs and returns
   * without marking anything when it cannot read the probe's sensors. The shadow then said
   * "already handled" for ever, and the sensors it never marked stayed Up (`P-77`).
   */
  offlineReason(probeObjectId: number): OfflineReason | undefined {
    return this.#byProbe.get(probeObjectId)?.reason;
  }

  /** Whether this sensor's probe is answering. Read on every state decision. */
  reachable(sensorId: number): boolean {
    return !this.#unreachable.has(sensorId);
  }

  /** The live set, for the state service to overlay onto what it loads. */
  unreachableSensors(): ReadonlySet<number> {
    return this.#unreachable;
  }

  /**
   * A probe stopped answering.
   *
   * The sensor list is read *now* rather than kept up to date, because it is only needed at this
   * moment and the tree it comes from is the tree as it was when the probe was last carrying it.
   * A sensor created while the probe is away is not in the set, and does not need to be: it has
   * never been scanned, so it is already Unknown for want of a reading.
   */
  async lost(probeObjectId: number, reason: OfflineReason = 'link'): Promise<number> {
    // Already offline for some reason. Whichever came first is the one an operator is reading,
    // and re-marking would re-walk the tree and re-evaluate for no change.
    if (this.#byProbe.has(probeObjectId)) return 0;

    let sensorIds: number[];
    try {
      sensorIds = await this.#sensorsUnder(probeObjectId);
    } catch (error) {
      // Not fatal, and not a reason to pretend the probe is up either: the set stays empty, the
      // sensors keep their last state, and the next disconnect tries again. A probe outage that
      // also cannot read the database is a bigger problem than this line.
      this.#logger.error(
        { probeObjectId, err: describeError(error) },
        'could not find the sensors a lost probe was carrying',
      );
      return 0;
    }

    this.#byProbe.set(probeObjectId, { sensorIds, reason });
    for (const id of sensorIds) this.#unreachable.add(id);
    this.#outages += 1;
    if (sensorIds.length === 0) return 0;

    // **The overlay is in place before the re-evaluation runs**, which is what makes this one
    // statement rather than a parameter threaded through the state machine: `reevaluate` loads
    // the facts, the service overlays `probeReachable` from this set, and layer 3 does the rest.
    //
    // And taken back out if the write does not land (`P-80`). The overlay has to go in first, but
    // leaving it in after a rejected transaction claims an outage that was never written: no
    // `sensor_state` row, every sensor still reading Up, and `offlineReason` answering 'silence'
    // for ever — so the delivery sweep, whose whole `P-77` fix was to read this instead of a
    // shadow set, would see "already handled" and never retry. The failure this rolls back is the
    // same shape as the one that fix was for, one layer down.
    let moved: number;
    try {
      moved = await this.#db.tx((q) =>
        this.#states.reevaluate(q, sensorIds, this.#now(), {
          message:
            reason === 'link'
              ? 'the probe carrying this sensor stopped answering'
              : 'the probe carrying this sensor is connected but has stopped sending results',
        }),
      );
    } catch (error) {
      this.#byProbe.delete(probeObjectId);
      for (const id of sensorIds) this.#unreachable.delete(id);
      this.#outages -= 1;
      // Returned rather than rethrown, for the reason the `#sensorsUnder` failure above gives:
      // one probe the database would not answer for must not abort the sweep over the others.
      this.#logger.error(
        { probeObjectId, reason, sensors: sensorIds.length, err: describeError(error) },
        'could not mark a lost probe’s sensors Unknown; leaving it unmarked so the next pass retries',
      );
      return 0;
    }
    this.#logger.warn(
      { probeObjectId, reason, sensors: sensorIds.length, moved },
      'a probe went offline; its sensors are Unknown rather than Down',
    );
    return moved;
  }

  /**
   * A probe answered again.
   *
   * Its sensors go back to whatever their **last reading** says, which is the honest answer:
   * that reading is the most recent thing the system actually measured, and the next scan —
   * within one interval — corrects it. Holding them Unknown until a fresh result arrived would
   * add a second transition per sensor for no information, and turn one outage into two.
   */
  async found(probeObjectId: number): Promise<number> {
    return this.#online(probeObjectId, undefined);
  }

  /**
   * A probe that had gone quiet is delivering again (`P-74`).
   *
   * Only clears what the delivery sweep itself marked. A probe whose *link* is down is not made
   * well by the sweep no longer expecting results from it, and letting this clear that entry
   * would put every sensor under a disconnected probe back to its last reading — a confident
   * answer about a probe nobody is talking to.
   */
  async resumed(probeObjectId: number): Promise<number> {
    return this.#online(probeObjectId, 'silence');
  }

  async #online(probeObjectId: number, only: OfflineReason | undefined): Promise<number> {
    const entry = this.#byProbe.get(probeObjectId);
    if (entry === undefined) return 0;
    if (only !== undefined && entry.reason !== only) return 0;
    const sensorIds = entry.sensorIds;
    this.#byProbe.delete(probeObjectId);
    for (const id of sensorIds) this.#unreachable.delete(id);
    if (sensorIds.length === 0) return 0;

    // The mirror of `lost`'s rollback, and it was missing (`P-90`). The overlay is dropped
    // before the write, so a rejected transaction left the database holding `unknown`/`probe`
    // for every sensor while this process believed the probe was fine: `offlineReason` returns
    // undefined, the sweep's `held === 'silence'` branch can never fire again, and the retry
    // path is gone — the same way `P-77`'s shadow set lost it. The recovery transition is then
    // a permanent hole in the history uptime is computed from.
    //
    // Not rethrown, for the reason `lost` gives: the rejection would otherwise escape
    // `resumed()` into `ProbeDeliveryWatch.settle()`, which documents itself as never throwing,
    // and every probe after this one in the pass would be skipped.
    let moved: number;
    try {
      moved = await this.#db.tx((q) =>
        this.#states.reevaluate(q, sensorIds, this.#now(), {
          message: 'the probe carrying this sensor is answering again',
        }),
      );
    } catch (error) {
      this.#byProbe.set(probeObjectId, entry);
      for (const id of sensorIds) this.#unreachable.add(id);
      this.#logger.error(
        { probeObjectId, sensors: sensorIds.length, err: describeError(error) },
        'could not clear a returning probe’s sensors; leaving them marked so the next pass retries',
      );
      return 0;
    }
    this.#logger.info(
      { probeObjectId, sensors: sensorIds.length, moved },
      'a probe came back; its sensors returned to their last reading',
    );
    return moved;
  }

  /**
   * Every sensor beneath a probe.
   *
   * A recursive walk of the adjacency tree rather than a path column: the tree is at most
   * probe → group → … → device → sensor, and this runs once per probe outage rather than once
   * per anything. `S-04`'s own subtree read is the same shape.
   */
  async #sensorsUnder(probeObjectId: number): Promise<number[]> {
    const rows = await this.#db.query<{ id: string }>(
      // The core-evaluated exclusion is a NOT IN rather than a filter applied afterwards, so a
      // probe carrying five thousand sensors and one Sensor Factory does not read the factory's
      // row only to throw it away — and so the empty-list case is one array parameter rather
      // than a second statement.
      `WITH RECURSIVE below AS (
         SELECT id, kind FROM object WHERE id = $1
         UNION ALL
         SELECT child.id, child.kind
         FROM object child JOIN below ON child.parent_id = below.id
       )
       SELECT below.id::text AS id
       FROM below
       JOIN sensor_config ON sensor_config.object_id = below.id
       WHERE below.kind = 'sensor' AND NOT (sensor_config.type = ANY($2::text[]))`,
      [probeObjectId, [...this.#coreEvaluatedTypes]],
    );
    return rows.map((row) => Number(row.id));
  }
}
