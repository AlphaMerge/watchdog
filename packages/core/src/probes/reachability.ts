import { describeError, type CheckFailure, type Logger } from '@ms/shared';
import { savepoint, type Queryable } from '../db/pool.js';
import { MAX_WALK_DEPTH } from '../db/walk.js';
import { heldIn, type HeldWords, type HeldWordsLookup } from '../state/runtime.js';

/**
 * Which probes are reachable, and what that means for their sensors (`R-05`).
 *
 * **A lost probe is one alarm, not a thousand.** When a probe stops answering, the sensors it
 * carries have not failed — nobody has asked them anything. Reporting them Down would be a claim
 * the system cannot support and would page whoever is on call with one alarm per sensor for a
 * single cable. `WORKFLOW.MD §12` and `docs/state-machine.md` layer 3 already say the right
 * thing: those sensors are **Unknown, cause `probe`**, and the one alarm comes from Probe Health.
 * This is the wiring that makes it happen — the state machine has always known how to answer,
 * and until now nothing ever told it the probe was gone.
 *
 * **Held in memory and never persisted, deliberately.** `probeReachable` is a live fact about a
 * TCP connection; a value read back from a table would be a claim about the past. A core that
 * has just started has not yet learned that a probe is missing, so `loadRuntimes` restores it
 * optimistically — and restoring it pessimistically would write a "probe unreachable" transition
 * for every sensor in the installation on every restart, an alarm storm generated by the restart
 * itself. The cost of the optimistic answer is one interval of staleness after a restart, which
 * the probe's own reconnect or its absence corrects.
 */

interface Db {
  query<T extends Record<string, unknown>>(text: string, values?: readonly unknown[]): Promise<T[]>;
  tx<T>(fn: (q: Queryable) => Promise<T>): Promise<T>;
}

/** What this needs from the state service: re-decide these sensors, and say how many moved. */
export interface StateReevaluator {
  reevaluate(
    q: Queryable,
    sensorIds: readonly number[],
    at: Date,
    /**
     * The words, and the one cause they speak for: the probe's (`R-11`). A sensor this lets go
     * carries them until its next result, and one it holds for the probe carries them while held.
     * `failure` is where the check stopped, passed only by a hold whose words are a result's
     * (`P-265`, `P-407`), and stored beside them while they are what the sensor says. A sensor
     * its probe could not start says its probe's latest round, read live whoever re-decides it
     * (`P-410`): these are what a transition says when nothing live answers.
     */
    cause: {
      message: string;
      sources: readonly 'probe'[];
      failure?: CheckFailure | null;
    },
  ): Promise<number>;
}

/** And what this alone needs of it, because only this changes an overlay a rollback puts back. */
export interface ReachabilityStates extends StateReevaluator {
  /**
   * Drop what is cached about these sensors, so their next result is decided from the stored row
   * (`P-253`). Since `P-412` a result decided against an overlay a rollback has since put back is
   * cached as its row has it, and the next result reads the overlay live; what a rollback still
   * needs is the owing (`retryGivenUp`), for a sensor that sends no result.
   */
  forgetSensors(sensorIds: readonly number[]): void;
}

/** What the probe paths speak for when they re-decide a sensor (`R-11`). */
export const PROBE_SOURCE: readonly 'probe'[] = ['probe'];

/** What a sensor whose probe's link has gone says while it is held (`R-05`). */
export const LOST_MESSAGE = 'the probe carrying this sensor stopped answering';

/** What a sensor whose probe is connected and sends nothing says while it is held (`P-74`). */
export const SILENT_MESSAGE =
  'the probe carrying this sensor is connected but has stopped sending results';

/** Each reason's words, which name no place a check stopped: no check ran (`P-413`). */
const HELD_WORDS: Readonly<Record<OfflineReason, HeldWords>> = {
  link: { message: LOST_MESSAGE, failure: null },
  silence: { message: SILENT_MESSAGE, failure: null },
};

export interface ProbeReachabilityOptions {
  db: Db;
  logger: Logger;
  states: ReachabilityStates;
  /**
   * Sensor types the **core** evaluates, which a probe outage does not touch (`P-13`).
   *
   * Found while building Probe Health, and it was already wrong for `core.factory`. A
   * core-evaluated sensor's readings come from rows this process holds; the probe it happens to
   * sit under has never scanned it and its absence changes nothing about it. Marking it Unknown
   * for that reason is a false claim — and for Probe Health specifically it is a disabling one,
   * because the sensor whose job is to raise the single alarm for a lost probe would be silenced
   * by the very outage it exists to report.
   *
   * Absent, nothing is excluded, which is the behaviour before this.
   */
  coreEvaluatedTypes?: readonly string[];
  /**
   * Recomputes `paused_by_dependency` after this has moved sensors (`P-135`).
   *
   * **Required, not optional.** A probe going away moves its sensors to Unknown, and a master
   * that is Unknown is not Down — so anything it was holding must be released. Nothing ran that:
   * the dependency reaction is reachable from ingestion, with the transitions a *result batch*
   * produced, and a probe that has gone produces no results. The dependents kept
   * `paused_by_dependency`, dropped out of the probe configuration, and were never scanned
   * again — while the pause API, which computes what is holding them from the master's *current*
   * state, reported nothing holding them and refused to resume them. That is `P-87`'s failure
   * exactly, reached down a path `P-87` did not cover.
   *
   * Required for the reason `P-111` gives: a wiring line that can be deleted with every test
   * still green is a wiring line that will be.
   */
  dependencies: DependencyRecomputer;
  /**
   * The sensors that are a probe's own alarm: its Probe Health (`M-22`).
   *
   * Re-evaluated with the sensors the probe carries, on the way out and on the way back, so the
   * alarm engine reconciles them in the same transaction. A trigger on Unknown sees a lost
   * probe's live Probe Health as Unknown, and that view has to move when the carried sensors do.
   * Probe Health may have gone Down at its own sweep before the probe was declared lost, and
   * then it has no transition left to react on. Absent, nothing is added.
   */
  probeAlarms?: (probeObjectId: number) => readonly number[];
  now?: () => Date;
}

/** What one offline probe holds, and why, and since when. */
interface HeldBy {
  readonly sensorIds: number[];
  readonly reason: OfflineReason;
  readonly since: Date;
}

/**
 * How many sensors may be owed a re-decision at once (`P-249`). The installation's sensor count
 * bounds it in practice; this bounds it if something keeps failing.
 */
const MAX_GIVEN_UP = 50_000;
/** How many of their ids a log line names. */
const GIVEN_UP_LOGGED = 50;

/** Just enough of `DependencyPauses` to settle the flags after sensors have moved. */
export interface DependencyRecomputer {
  recompute(q: Queryable, at: Date): Promise<{ moved: number }>;
}

/**
 * Why a probe's sensors are Unknown.
 *
 * `link` is `R-05`: the connection went away, so nobody is asking. `silence` is `P-74`: the
 * connection is fine and nothing is coming back, which the sensors cannot tell apart and an
 * operator very much can.
 */
export type OfflineReason = 'link' | 'silence';

export class ProbeReachability {
  readonly #db: Db;
  readonly #logger: Logger;
  readonly #states: ReachabilityStates;
  readonly #dependencies: DependencyRecomputer;
  readonly #coreEvaluatedTypes: readonly string[];
  readonly #probeAlarms: (probeObjectId: number) => readonly number[];
  readonly #now: () => Date;

  /**
   * The sensors whose probe is currently gone.
   *
   * Sensor ids rather than probe ids, because the question asked of it — a hundred times a
   * second, once per sensor whose state is being decided — is "is *this* sensor's probe up".
   * Answering that from probe ids would mean walking the tree for every sensor on every
   * decision; a set of at most the installation's sensor count is a few hundred kilobytes at
   * the v1 target of 5,000 and answers in constant time.
   */
  readonly #unreachable = new Set<number>();
  /** Which probe put each sensor in that set, so one probe's return frees only its own. */
  /**
   * Why each probe's sensors are Unknown, alongside which they are.
   *
   * **The reason is here so that only its owner can clear it** (`P-74`). A probe that is
   * connected and silent and a probe whose link has gone both put their sensors in the same set,
   * because the sensors' answer is the same — but the delivery sweep must not decide a
   * *disconnected* probe is fine again just because it has stopped expecting results from it.
   * `found` is the link's, `resumed` is the sweep's, and neither undoes the other's work.
   */
  readonly #byProbe = new Map<number, HeldBy>();
  /** Which probe holds each sensor in `#unreachable`, for the alarm engine's hold (`M-22`). */
  readonly #carrier = new Map<number, number>();
  /**
   * `#unreachable` by the reason that holds each sensor, kept with it (`P-413`), and each one's
   * words read from it: the state service resolves a lost link's before a silence's, as it does
   * every hold's, so neither reason's words go first-come.
   */
  readonly #byReason: Readonly<Record<OfflineReason, Set<number>>> = {
    link: new Set(),
    silence: new Set(),
  };
  readonly #words: Readonly<Record<OfflineReason, HeldWordsLookup>> = {
    link: heldIn(() => this.#byReason.link, HELD_WORDS.link),
    silence: heldIn(() => this.#byReason.silence, HELD_WORDS.silence),
  };
  /**
   * Sensors whose re-decision a resync gave up (`P-249`), owed one by the next resync or delivery
   * sweep. At most `MAX_GIVEN_UP`; past that the rest are logged as dropped.
   *
   * **Each with the owing that put it here** (`P-253`). A settlement clears only the owings it
   * read when it started, so one that a rollback makes while a re-decision is in flight — a
   * re-decision that read the overlay the rollback has just put back — outlasts it.
   */
  readonly #givenUp = new Map<number, number>();
  #owings = 0;
  #outages = 0;
  /**
   * Each probe's `lost`, `found` and `resumed`, one at a time and in the order they were called
   * (`P-416`), each whole: what it changes in the overlay, and the re-decision that follows.
   *
   * They used to change the overlay as they were called and then re-decide the probe's sensors
   * in a transaction of their own, from an unlocked read (`P-414`). A `lost` that arrived while
   * `found`'s transaction was still writing read the hold's Unknown it had not yet replaced,
   * decided nothing, and `found` then committed the last reading for a probe that was gone, with
   * nothing to re-decide it while it stayed away; a `found` during `lost`'s write left a connected
   * probe's sensors Unknown; and a `found` during `lost`'s tree read found no hold to let go of.
   * Only the transactions waiting is not enough: a call's overlay change would then reach a
   * re-decision still in flight, which decides under it in the other call's words. So a call's
   * overlay change waits for the turn before it as well, a few milliseconds at most, and a result
   * decided meanwhile sees the overlay as it was (`P-418`).
   */
  readonly #turns = new Map<number, Promise<void>>();

  constructor(options: ProbeReachabilityOptions) {
    this.#db = options.db;
    this.#logger = options.logger.child({ component: 'probe-reachability' });
    this.#states = options.states;
    this.#coreEvaluatedTypes = options.coreEvaluatedTypes ?? [];
    this.#dependencies = options.dependencies;
    this.#probeAlarms = options.probeAlarms ?? ((): readonly number[] => []);
    this.#now = options.now ?? ((): Date => new Date());
  }

  stats(): {
    probesDown: number;
    probesSilent: number;
    sensorsUnknown: number;
    outages: number;
    sensorsOwedRedecision: number;
  } {
    // **Split by reason** (`P-80`). `probesDown` is published to Core Health as 'Probes not
    // connected', and `P-74` began putting `reason: 'silence'` entries into this same map — for
    // probes whose session is up and heartbeating. The number then contradicted that probe's own
    // Probe Health, which reported it connected, and sent operators looking for a network fault
    // while the true signal was buried under the disagreement.
    let silent = 0;
    for (const held of this.#byProbe.values()) if (held.reason === 'silence') silent += 1;
    return {
      probesDown: this.#byProbe.size - silent,
      probesSilent: silent,
      sensorsUnknown: this.#unreachable.size,
      outages: this.#outages,
      // Core Health's reading of them (`P-400`): the same number `givenUp()` answers.
      sensorsOwedRedecision: this.#givenUp.size,
    };
  }

  /**
   * Whether any probe is held offline, so that `resync` has anything to do. The normal state of
   * an installation is no, and then a tree change costs `ReachabilitySync` no statement at all.
   */
  holdsAny(): boolean {
    return this.#byProbe.size > 0;
  }

  /**
   * Re-derives the overlay from the tree, after the tree has changed (`P-103`).
   *
   * `lost` snapshots a probe's sensors once, and that snapshot outlived the topology it was
   * taken from. A sensor moved off a dead probe onto a live one kept `probeReachable: false`
   * for as long as the dead probe stayed away — permanently, if it was decommissioned, which is
   * the usual reason somebody moves a device off it. Every result then short-circuited at layer
   * 3 to `unknown`/`probe`; no transition was recorded, because the state did not change, and
   * the sensors were dark and unalarmable while their new probe scanned them happily. Nothing in
   * the code or `docs/state-machine.md` had a name for "a sensor whose current probe is
   * delivering but which the core still believes is behind a lost one".
   *
   * The mirror case is a sensor *arriving* under a probe that is already away — by a move, a
   * create, a clone or a discovery — which the snapshot could not see either.
   *
   * **Through the caller's transaction**, because the tree change it is reacting to has not
   * committed yet. Reading on another connection would see the tree as it was before the move —
   * which is the whole thing being corrected, and is the same mistake `P-88` found in the delete
   * path from the other direction.
   *
   * **Free when nothing is offline**, which is the normal state of an installation: an empty map
   * means there is no overlay for a topology change to invalidate. Otherwise it costs one
   * subtree read per offline probe, on a mutation that is already walking the tree.
   *
   * Re-read rather than patched. Working out which sensors a move added or removed means walking
   * the tree anyway, and a snapshot that is *recomputed* cannot drift from the tree in the way
   * the one it replaces did.
   *
   * **Each of its two catches is around a savepoint** (`P-249`). Both carry on after a failed
   * statement, inside a transaction that is the caller's, and a failed statement aborts it: the
   * caller's `COMMIT` would then roll back the move this exists to follow, and every other write
   * in it. Rolled back to the savepoint instead, the move commits and only this read is lost.
   *
   * **And what it changes in memory is put back if the caller's transaction does not commit**
   * (`P-249`). The overlay changes here, before the commit, because the state service and the
   * alarm engine read it inside this same transaction to re-decide what moved. A sink after this
   * one can still fail and roll the move back, and an overlay left describing the tree as the
   * move would have made it held a sensor still under its live probe Unknown for every result
   * that probe sent, or the reverse: `P-103`'s defect, reached by a rollback. So the change is
   * undone in `afterRollback`, probe by probe, and only where nothing has replaced it since —
   * and what it re-decided is forgotten and owed again, because a result decided meanwhile on
   * another connection read the overlay this changed (`P-253`).
   *
   * **Sensors whose re-decision was given up are re-decided later** (`P-249`). The overlay is
   * right once this has run, and the next resync would see nothing cross it, while a sensor
   * behind an offline probe sends no result to settle it. So they are kept, a bounded set, and
   * re-decided by the next resync or the delivery sweep's `retryGivenUp`, whichever is first.
   */
  async resync(q: Queryable): Promise<number> {
    if (this.#byProbe.size === 0) return 0;

    const before = new Set(this.#unreachable);
    // And which of them a lost link held, since a move between a probe whose link is lost and one
    // that is silent keeps the sensor held but changes whose words it says (`P-413`).
    const beforeLink = new Set(this.#byReason.link);
    // The probes whose held set this changes, to or from empty included (`M-24`), and the entry
    // each had, which a rollback puts back.
    const replaced = new Map<number, { was: HeldBy; now: HeldBy }>();
    for (const [probeObjectId, held] of this.#byProbe) {
      try {
        const sensorIds = await savepoint(q, (inner) => this.#sensorsUnder(probeObjectId, inner));
        if (!sameMembers(sensorIds, held.sensorIds)) {
          replaced.set(probeObjectId, { was: held, now: { ...held, sensorIds } });
        }
      } catch (error) {
        // Leave this probe's snapshot as it was, for the reason `lost` gives: one probe the
        // database will not answer for must not discard the overlay for the others.
        this.#logger.error(
          { probeObjectId, err: describeError(error) },
          'could not re-read a lost probe’s sensors after a topology change',
        );
      }
    }

    // Only over an entry nothing has replaced while the tree was being read: a `found` or a `lost`
    // in between is newer than this, and is kept.
    const applied = new Map<number, { was: HeldBy; now: HeldBy }>();
    for (const [probeObjectId, change] of replaced) {
      if (this.#byProbe.get(probeObjectId) !== change.was) continue;
      this.#byProbe.set(probeObjectId, change.now);
      applied.set(probeObjectId, change);
    }
    if (applied.size > 0) this.#rebuild();
    const touched = new Set(applied.keys());

    // Both directions: sensors that left an offline probe go back to what their last reading
    // says, and sensors that arrived under one become Unknown. Only the ones that actually
    // moved across the boundary — the rest have nothing to re-decide. **And those that moved
    // between a lost link and a silence** (`P-413`): still held, so no transition, but each says
    // its hold's words, and a lost link's are not a silent probe's. A sensor held for both says
    // the link's, so the link's set alone says whether its words changed.
    const changed = [
      ...[...before].filter((id) => !this.#unreachable.has(id)),
      ...[...this.#unreachable].filter(
        (id) => !before.has(id) || beforeLink.has(id) !== this.#byReason.link.has(id),
      ),
    ];
    // And whatever an earlier resync gave up re-deciding, which nothing else will.
    const owing = [...this.#givenUp];
    const owed = owing.map(([id]) => id);
    if (changed.length === 0 && touched.size === 0 && owed.length === 0) return 0;
    // **And the alarm of every probe whose held set changed** (`M-24`), with them. Sensors that
    // arrive under a probe lost while it carried nothing are held behind its Probe Health, and
    // that alarm was never re-decided, so a trigger on Unknown heard nothing for the outage. A
    // probe whose last sensors were moved off it has an episode that ended, and its alarm is owed
    // the all-clear.
    const alarms = [...touched].flatMap((probeObjectId) => this.#probeAlarms(probeObjectId));
    const redecide = [...new Set([...changed, ...alarms, ...owed])];
    if (applied.size > 0) this.#undoOnRollback(q, applied, redecide);

    try {
      const moved = await savepoint(q, async (inner) => {
        const count = await this.#states.reevaluate(inner, redecide, this.#now(), {
          message: 'the probe carrying this sensor changed',
          sources: PROBE_SOURCE,
        });
        // In the same transaction: a master that has just become Unknown is not Down, so anything
        // it was holding is released here rather than at whatever recomputes next (`P-135`).
        await this.#dependencies.recompute(inner, this.#now());
        return count;
      });
      this.#settled(q, owing);
      this.#logger.info(
        { sensors: changed.length, owed: owed.length, moved },
        'the tree moved sensors across a lost probe’s boundary',
      );
      return moved;
    } catch (error) {
      // The overlay is right; only the stored states are behind. Rolling the overlay back would
      // put the stale snapshot the whole method exists to remove straight back in, so the
      // sensors are owed a re-decision instead.
      this.#giveUp(redecide, error);
      return 0;
    }
  }

  /**
   * Re-decides, in a transaction of its own, the sensors a resync gave up re-deciding (`P-249`).
   * The delivery sweep calls it every pass. Never throws: what fails stays owed for the next.
   */
  async retryGivenUp(): Promise<number> {
    const owing = [...this.#givenUp];
    const owed = owing.map(([id]) => id);
    if (owed.length === 0) return 0;
    try {
      const moved = await this.#db.tx(async (q) => {
        const count = await this.#states.reevaluate(q, owed, this.#now(), {
          message: 'the probe carrying this sensor changed',
          sources: PROBE_SOURCE,
        });
        await this.#dependencies.recompute(q, this.#now());
        return count;
      });
      this.#settle(owing);
      this.#logger.info({ sensors: owed.length, moved }, 'sensors owed a re-decision settled');
      return moved;
    } catch (error) {
      this.#logger.error(
        { sensors: owed.slice(0, GIVEN_UP_LOGGED), owed: owed.length, err: describeError(error) },
        'could not re-decide the sensors a tree change left owed; the next sweep tries again',
      );
      return 0;
    }
  }

  /** How many sensors are owed a re-decision a resync gave up (`P-249`). */
  givenUp(): number {
    return this.#givenUp.size;
  }

  /** Owed no longer, once the transaction that re-decided them has committed. */
  #settled(q: Queryable, owing: readonly (readonly [number, number])[]): void {
    if (owing.length === 0) return;
    const settle = (): void => {
      this.#settle(owing);
    };
    if (q.afterCommit === undefined) settle();
    else q.afterCommit(settle);
  }

  /**
   * Clears the owings a committed re-decision read, and only those (`P-253`), and drops what is
   * cached about them, so the next result is decided from the stored row. A read that straddled a
   * rollback — its rows arrived before the undo and it cached them after — held the overlay the
   * rollback put back until `P-412`, which caches no overlay.
   */
  #settle(owing: readonly (readonly [number, number])[]): void {
    for (const [id, owingNumber] of owing) {
      if (this.#givenUp.get(id) === owingNumber) this.#givenUp.delete(id);
    }
    this.#states.forgetSensors(owing.map(([id]) => id));
  }

  /**
   * Puts the overlay back if the caller's transaction does not commit, and owes what it moved a
   * re-decision (`P-249`, `P-253`).
   *
   * **Putting the overlay back is not enough on its own.** A result for a moved sensor decided on
   * another connection while the move was open reads the stored row and lays this overlay over
   * it, and the state service caches that: a sensor still under its live probe, decided Unknown
   * against a move that never committed, went on being decided Unknown from its cache for every
   * result that probe sent, and the ingest write that waited on the move's row lock stored it
   * so. So what was re-decided is forgotten, and owed to the delivery sweep, which re-decides it
   * against the overlay as it is again — a sensor behind a lost probe sends no result to do it.
   */
  #undoOnRollback(
    q: Queryable,
    applied: ReadonlyMap<number, { was: HeldBy; now: HeldBy }>,
    redecide: readonly number[],
  ): void {
    q.afterRollback?.(() => {
      for (const [probeObjectId, change] of applied) {
        if (this.#byProbe.get(probeObjectId) === change.now) {
          this.#byProbe.set(probeObjectId, change.was);
        }
      }
      this.#rebuild();
      this.#states.forgetSensors(redecide);
      const dropped = this.#owe(redecide);
      this.#logger.info(
        { probes: [...applied.keys()], owed: this.#givenUp.size, dropped },
        'a tree change rolled back; the lost probes’ sensors are as they were before it, and ' +
          'what it re-decided is re-decided again at the next delivery sweep',
      );
    });
  }

  /**
   * Owes these sensors a re-decision, up to the bound. Returns how many did not fit. One already
   * owed is owed afresh, so a settlement already in flight does not clear it (`P-253`).
   */
  #owe(sensorIds: readonly number[]): number {
    this.#owings += 1;
    let dropped = 0;
    for (const id of sensorIds) {
      if (this.#givenUp.has(id) || this.#givenUp.size < MAX_GIVEN_UP) {
        this.#givenUp.set(id, this.#owings);
      } else dropped += 1;
    }
    return dropped;
  }

  #giveUp(sensorIds: readonly number[], error: unknown): void {
    const dropped = this.#owe(sensorIds);
    this.#logger.error(
      {
        sensors: sensorIds.slice(0, GIVEN_UP_LOGGED),
        count: sensorIds.length,
        owed: this.#givenUp.size,
        dropped,
        err: describeError(error),
      },
      'could not re-evaluate sensors after a topology change; the overlay is correct, and they ' +
        'are re-decided at the next resync or delivery sweep',
    );
  }

  /** `#unreachable`, `#carrier` and `#byReason`, from `#byProbe`. */
  #rebuild(): void {
    this.#unreachable.clear();
    this.#carrier.clear();
    this.#byReason.link.clear();
    this.#byReason.silence.clear();
    for (const [probeObjectId, held] of this.#byProbe) {
      this.#hold(probeObjectId, held.reason, held.sensorIds);
    }
  }

  /**
   * Why this probe's sensors are Unknown, or `undefined` if they are not.
   *
   * **So a caller can tell an edge from a level without keeping its own copy.** The delivery
   * sweep did keep one, and the copy could diverge from this in the one direction that matters:
   * it recorded a probe as marked *before* `lost` had succeeded, and `lost` logs and returns
   * without marking anything when it cannot read the probe's sensors. The shadow then said
   * "already handled" for ever, and the sensors it never marked stayed Up (`P-77`).
   */
  offlineReason(probeObjectId: number): OfflineReason | undefined {
    return this.#byProbe.get(probeObjectId)?.reason;
  }

  /** Whether this sensor's probe is answering. Read on every state decision. */
  reachable(sensorId: number): boolean {
    return !this.#unreachable.has(sensorId);
  }

  /** The live set: every sensor held, for either reason. */
  unreachableSensors(): ReadonlySet<number> {
    return this.#unreachable;
  }

  /**
   * The sensors held for one reason, each with what it says while held (`P-413`): what the state
   * service lays over the facts, and says, after any hold above it. A view over the live set.
   */
  heldWords(reason: OfflineReason): HeldWordsLookup {
    return this.#words[reason];
  }

  /** What this probe's absence holds, and since when, while it does (`M-22`). */
  heldBy(
    probeObjectId: number,
  ): { sensorIds: readonly number[]; reason: OfflineReason; since: Date } | undefined {
    return this.#byProbe.get(probeObjectId);
  }

  /** The probe whose absence holds this sensor Unknown, while one does (`M-22`). */
  carrierOf(sensorId: number): number | undefined {
    return this.#carrier.get(sensorId);
  }

  /**
   * A probe stopped answering.
   *
   * The sensor list is read *now* rather than kept up to date, because it is only needed at this
   * moment and the tree it comes from is the tree as it was when the probe was last carrying it.
   * A sensor created while the probe is away is not in the set, and does not need to be: it has
   * never been scanned, so it is already Unknown for want of a reading.
   */
  async lost(probeObjectId: number, reason: OfflineReason = 'link'): Promise<number> {
    return this.#inTurn(probeObjectId, () => this.#lose(probeObjectId, reason));
  }

  async #lose(probeObjectId: number, reason: OfflineReason): Promise<number> {
    // Already offline for some reason. Whichever came first is the one an operator is reading,
    // and re-marking would re-walk the tree and re-evaluate for no change.
    if (this.#byProbe.has(probeObjectId)) return 0;

    let sensorIds: number[];
    try {
      sensorIds = await this.#sensorsUnder(probeObjectId);
    } catch (error) {
      // Not fatal, and not a reason to pretend the probe is up either: the set stays empty, the
      // sensors keep their last state, and the next disconnect tries again. A probe outage that
      // also cannot read the database is a bigger problem than this line.
      this.#logger.error(
        { probeObjectId, err: describeError(error) },
        'could not find the sensors a lost probe was carrying',
      );
      return 0;
    }

    this.#byProbe.set(probeObjectId, { sensorIds, reason, since: this.#now() });
    this.#hold(probeObjectId, reason, sensorIds);
    this.#outages += 1;
    // Nothing held, so no episode begins and there is no alarm to re-decide. Sensors that arrive
    // later begin one, and `resync` re-decides the probe's alarm with them (`M-24`).
    if (sensorIds.length === 0) return 0;

    // **The overlay is in place before the re-evaluation runs**, which is what makes this one
    // statement rather than a parameter threaded through the state machine: `reevaluate` loads
    // the facts, the service overlays `probeReachable` from this set, and layer 3 does the rest.
    //
    // And taken back out if the write does not land (`P-80`). The overlay has to go in first, but
    // leaving it in after a rejected transaction claims an outage that was never written: no
    // `sensor_state` row, every sensor still reading Up, and `offlineReason` answering 'silence'
    // for ever — so the delivery sweep, whose whole `P-77` fix was to read this instead of a
    // shadow set, would see "already handled" and never retry. The failure this rolls back is the
    // same shape as the one that fix was for, one layer down.
    let moved: number;
    try {
      moved = await this.#db.tx(async (q) => {
        const count = await this.#states.reevaluate(
          q,
          [...sensorIds, ...this.#probeAlarms(probeObjectId)],
          this.#now(),
          // The words the sensors say come from `heldWords`, whoever re-decides them (`P-413`);
          // these are the same, for a caller that reads no hold.
          { message: HELD_WORDS[reason].message, sources: PROBE_SOURCE },
        );
        // **The dependents of a master under this probe** (`P-135`). The master is Unknown now,
        // not Down, so nothing is holding them — and nothing else was ever going to notice: the
        // dependency reaction runs on the transitions a result batch produced, and a probe that
        // has gone produces no results.
        await this.#dependencies.recompute(q, this.#now());
        return count;
      });
    } catch (error) {
      // As a resync has left it, which may have re-read the probe's sensors meanwhile; nothing
      // else changes this probe's entry while its turn runs (`P-416`).
      this.#release(this.#byProbe.get(probeObjectId)?.sensorIds ?? sensorIds);
      this.#byProbe.delete(probeObjectId);
      this.#outages -= 1;
      // Returned rather than rethrown, for the reason the `#sensorsUnder` failure above gives:
      // one probe the database would not answer for must not abort the sweep over the others.
      this.#logger.error(
        { probeObjectId, reason, sensors: sensorIds.length, err: describeError(error) },
        'could not mark a lost probe’s sensors Unknown; leaving it unmarked so the next pass retries',
      );
      return 0;
    }
    this.#logger.warn(
      { probeObjectId, reason, sensors: sensorIds.length, moved },
      'a probe went offline; its sensors are Unknown rather than Down',
    );
    return moved;
  }

  /**
   * A probe answered again.
   *
   * Its sensors go back to whatever their **last reading** says, which is the honest answer:
   * that reading is the most recent thing the system actually measured, and the next scan —
   * within one interval — corrects it. Holding them Unknown until a fresh result arrived would
   * add a second transition per sensor for no information, and turn one outage into two.
   */
  async found(probeObjectId: number): Promise<number> {
    return this.#inTurn(probeObjectId, () => this.#online(probeObjectId, undefined));
  }

  /**
   * A probe that had gone quiet is delivering again (`P-74`).
   *
   * Only clears what the delivery sweep itself marked. A probe whose *link* is down is not made
   * well by the sweep no longer expecting results from it, and letting this clear that entry
   * would put every sensor under a disconnected probe back to its last reading — a confident
   * answer about a probe nobody is talking to.
   */
  async resumed(probeObjectId: number): Promise<number> {
    return this.#inTurn(probeObjectId, () => this.#online(probeObjectId, 'silence'));
  }

  async #online(probeObjectId: number, only: OfflineReason | undefined): Promise<number> {
    const entry = this.#byProbe.get(probeObjectId);
    if (entry === undefined) return 0;
    if (only !== undefined && entry.reason !== only) return 0;
    const sensorIds = entry.sensorIds;
    this.#byProbe.delete(probeObjectId);
    this.#release(sensorIds);
    // An empty set still re-decides the probe's alarm (`M-24`): an episode emptied by a tree
    // change whose own re-evaluation did not land left an alarm that this is the last chance to
    // recover.
    const alarms = this.#probeAlarms(probeObjectId);
    if (sensorIds.length === 0 && alarms.length === 0) return 0;

    // The mirror of `lost`'s rollback, and it was missing (`P-90`). The overlay is dropped
    // before the write, so a rejected transaction left the database holding `unknown`/`probe`
    // for every sensor while this process believed the probe was fine: `offlineReason` returns
    // undefined, the sweep's `held === 'silence'` branch can never fire again, and the retry
    // path is gone — the same way `P-77`'s shadow set lost it. The recovery transition is then
    // a permanent hole in the history uptime is computed from.
    //
    // Not rethrown, for the reason `lost` gives: the rejection would otherwise escape
    // `resumed()` into `ProbeDeliveryWatch.settle()`, which documents itself as never throwing,
    // and every probe after this one in the pass would be skipped.
    let moved: number;
    try {
      moved = await this.#db.tx(async (q) => {
        const count = await this.#states.reevaluate(q, [...sensorIds, ...alarms], this.#now(), {
          message:
            'the probe carrying this sensor is answering again; until its next result it ' +
            'stands where it stood before the probe was lost',
          sources: PROBE_SOURCE,
        });
        // And the other direction: a master that is Down again holds what it should.
        await this.#dependencies.recompute(q, this.#now());
        return count;
      });
    } catch (error) {
      this.#byProbe.set(probeObjectId, entry);
      this.#hold(probeObjectId, entry.reason, sensorIds);
      this.#logger.error(
        { probeObjectId, sensors: sensorIds.length, err: describeError(error) },
        'could not clear a returning probe’s sensors; leaving them marked so the next pass retries',
      );
      return 0;
    }
    this.#logger.info(
      { probeObjectId, sensors: sensorIds.length, moved },
      'a probe came back; its sensors returned to their last reading',
    );
    return moved;
  }

  /** `work`, once every call for this probe made before it has settled (`P-416`). */
  async #inTurn<T>(probeObjectId: number, work: () => Promise<T>): Promise<T> {
    const before = this.#turns.get(probeObjectId);
    let done = (): void => undefined;
    const mine = new Promise<void>((resolve) => {
      done = resolve;
    });
    this.#turns.set(probeObjectId, mine);
    try {
      if (before !== undefined) await before;
      return await work();
    } finally {
      done();
      if (this.#turns.get(probeObjectId) === mine) this.#turns.delete(probeObjectId);
    }
  }

  #hold(probeObjectId: number, reason: OfflineReason, sensorIds: readonly number[]): void {
    const byReason = this.#byReason[reason];
    for (const id of sensorIds) {
      this.#unreachable.add(id);
      this.#carrier.set(id, probeObjectId);
      byReason.add(id);
    }
  }

  #release(sensorIds: readonly number[]): void {
    for (const id of sensorIds) {
      this.#unreachable.delete(id);
      this.#carrier.delete(id);
      this.#byReason.link.delete(id);
      this.#byReason.silence.delete(id);
    }
  }

  /**
   * Every sensor beneath a probe.
   *
   * A recursive walk of the adjacency tree rather than a path column: the tree is at most
   * probe → group → … → device → sensor, and this runs once per probe outage rather than once
   * per anything. `S-04`'s own subtree read is the same shape.
   */
  async #sensorsUnder(probeObjectId: number, q: Queryable = this.#db): Promise<number[]> {
    const rows = await q.query<{ id: string }>(
      // The core-evaluated exclusion is a NOT IN rather than a filter applied afterwards, so a
      // probe carrying five thousand sensors and one Sensor Factory does not read the factory's
      // row only to throw it away — and so the empty-list case is one array parameter rather
      // than a second statement.
      `WITH RECURSIVE below AS (
         SELECT id, kind, 0 AS depth FROM object WHERE id = $1
         UNION ALL
         SELECT child.id, child.kind, below.depth + 1
         FROM object child JOIN below ON child.parent_id = below.id
         WHERE below.depth < ${String(MAX_WALK_DEPTH)}
       )
       SELECT below.id::text AS id
       FROM below
       JOIN sensor_config ON sensor_config.object_id = below.id
       WHERE below.kind = 'sensor' AND NOT (sensor_config.type = ANY($2::text[]))`,
      [probeObjectId, [...this.#coreEvaluatedTypes]],
    );
    return rows.map((row) => Number(row.id));
  }
}

/** Whether two lists of sensor ids hold the same sensors, whatever the order. */
function sameMembers(a: readonly number[], b: readonly number[]): boolean {
  if (a.length !== b.length) return false;
  const members = new Set(b);
  return a.every((id) => members.has(id));
}
